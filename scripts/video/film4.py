def lines(text,size,width):
    result=[];row=''
    for char in text:
        if char=='\n' or (row and f.font(size).getlength(row+char)>width):
            result.append(row);row='' if char=='\n' else char
        else:row+=char
    if row:result.append(row)
    return result

def para(c,text,x,y,size=30,width=1600,col=INK,gap=1.55,center=False):
    for row in lines(text,size,width):
        c.text(x,y,row,size,col,anchor='ma' if center else 'la');y+=size*gap
    return y

