def encode(task):
    begin,end,path=task;started=time.time();bad=[]
    cmd=[ffmpeg(),'-hide_banner','-loglevel','error','-y','-f','rawvideo','-pix_fmt','rgb24','-s','1920x1080','-r','30','-i','pipe:0','-an','-c:v','libx264','-preset','veryfast','-crf','19','-pix_fmt','yuv420p','-threads','2',str(path)]
    with open(str(path)+'.log','wb') as log:
        proc=subprocess.Popen(cmd,stdin=subprocess.PIPE,stderr=log,stdout=subprocess.DEVNULL)
        try:
            for i in range(begin,end):
                im,overflow=render_frame(i)
                if overflow:bad.extend([(i,x) for x in overflow])
                proc.stdin.write(im.tobytes())
            proc.stdin.close()
            if proc.wait():raise RuntimeError('Encoder failed: '+str(path))
        finally:
            if proc.poll() is None:proc.kill();proc.wait()
    return {'path':str(path),'frames':end-begin,'elapsed':round(time.time()-started,2),'overflow':bad[:20]}

def compose_voice(out):
    target_rate=24000;audio=np.zeros(TOTAL*target_rate,dtype=np.int16);checks=[]
    for i,item in enumerate(NARRATION):
        path=out/'voice'/f'{i:02d}.wav'
        with wave.open(str(path),'rb') as w:
            channels,rate=w.getnchannels(),w.getframerate();assert w.getsampwidth()==2
            vals=np.frombuffer(w.readframes(w.getnframes()),dtype='<i2').reshape(-1,channels).mean(1)
        n=int(len(vals)*target_rate/rate);converted=np.interp(np.arange(n)*rate/target_rate,np.arange(len(vals)),vals)
        available=int((item['end']-item['start'])*target_rate)
        assert n<=available, f'Narration {i} exceeds slot: {n/target_rate:.2f}s > {available/target_rate:.2f}s'
        start=round(item['start']*target_rate);audio[start:start+n]=converted.astype(np.int16)
        checks.append({'index':i,'duration':n/target_rate,'slot':item['end']-item['start'],'text':item['text']})
    dest=out/'narration.wav'
    with wave.open(str(dest),'wb') as w:w.setnchannels(1);w.setsampwidth(2);w.setframerate(target_rate);w.writeframes(audio.tobytes())
    (out/'voice-audit.json').write_text(json.dumps(checks,ensure_ascii=False,indent=2),encoding='utf8');return dest

def prepare_subtitles(out):
    """Build reusable captions from actual synthesized clip durations."""
    checks=json.loads((out/'voice-synthesis.json').read_text(encoding='utf-8-sig'))
    cues=[]
    for item,check in zip(NARRATION,checks):
        chunks=[];row=''
        for char in item['text']:
            row+=char
            if char in '。？！' or len(row)>=27:chunks.append(row);row=''
        if row:chunks.append(row)
        size=sum(map(len,chunks));start=item['start']
        for chunk in chunks:
            end=start+check['seconds']*len(chunk)/size;cues.append({'start':start,'end':end,'text':chunk});start=end
    (out/'subtitles.json').write_text(json.dumps(cues,ensure_ascii=False,indent=2),encoding='utf8')
    def stamp(t):
        n=round(t*1000);return f'{n//3600000:02d}:{n//60000%60:02d}:{n//1000%60:02d},{n%1000:03d}'
    (out/'字幕.srt').write_text('\n\n'.join(f'{i+1}\n{stamp(s["start"])} --> {stamp(s["end"])}\n{s["text"]}' for i,s in enumerate(cues))+'\n',encoding='utf8')
    return cues

