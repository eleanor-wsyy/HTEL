def sankey_geometry():
    positions={};scale=1.02;ys={};paths=[]
    for stage,var in enumerate(SK['variables']):
        node_list=[n for n in SK['nodes'] if n['stage']==stage]
        gap=(600-515*scale)/max(1,len(node_list)-1);y=295
        for n in node_list:
            positions[(stage,n['label'])]=(y,n['n']*scale);ys[(stage,n['label'])]=y;y+=n['n']*scale+gap
    for flow in SK['paths']:
        points=[]
        for j,label in enumerate(flow['labels']):
            key=(j,label);points.append(ys[key]);ys[key]+=flow['n']*scale
        paths.append((flow,points,flow['n']*scale))
    return positions,paths
